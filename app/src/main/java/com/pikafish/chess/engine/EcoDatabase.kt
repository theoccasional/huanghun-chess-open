    /**
     * 根据走法序列识别开局名称。
     *
     * 匹配策略：
     * 1. 将输入走法列表拼接为逗号分隔的字符串
     * 2. 按走法序列长度从长到短排序所有条目
     * 3. 遍历排序后的条目，第一个前缀匹配（entries.moves 以 movesStr 开头）的条目即为结果
     * 4. 若无匹配则返回 null
     *
     * @param moves 走法列表，每个元素为一步棋的中文走法表示，如 "炮二平五"
     * @return 匹配的开局名称，或 null
     */
    fun identifyOpening(moves: List<String>): String? {
        if (moves.isEmpty()) return null

        val movesStr = moves.joinToString(",")

        // 按走法长度降序排列，优先匹配更长的（更精确的）走法序列
        val sortedEntries = entries.sortedByDescending { it.moves.split(",").size }

        for (entry in sortedEntries) {
            if (movesStr.startsWith(entry.moves)) {
                return "${entry.code} ${entry.name}"
            }
        }

        return null
    }

    /**
     * 根据走法序列识别开局，返回完整的 EcoEntry 对象。
     *
     * @param moves 走法列表
     * @return 匹配的 EcoEntry 对象，或 null
     */
    fun identifyEntry(moves: List<String>): EcoEntry? {
        if (moves.isEmpty()) return null

        val movesStr = moves.joinToString(",")

        val sortedEntries = entries.sortedByDescending { it.moves.split(",").size }

        for (entry in sortedEntries) {
            if (movesStr.startsWith(entry.moves)) {
                return entry
            }
        }

        return null
    }

    /**
     * 按分类查找所有开局条目。
     *
     * @param category 分类名称，如 "中炮对屏风马"、"飞相局" 等
     * @return 该分类下的所有 EcoEntry
     */
    fun getEntriesByCategory(category: String): List<EcoEntry> {
        return entries.filter { it.category == category }
    }

    /**
     * 按 ECO 编号查找开局条目。
     *
     * @param code ECO 编号，如 "C77"
     * @return 对应的 EcoEntry，或 null
     */
    fun getEntryByCode(code: String): EcoEntry? {
        return entries.find { it.code == code }
    }

    /**
     * 获取所有分类名称。
     */
    fun getAllCategories(): List<String> {
        return entries.map { it.category }.distinct()
    }
