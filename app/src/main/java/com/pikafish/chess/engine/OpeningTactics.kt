 *
 * 参考节点象棋、象棋笔记的做法：识别出开局后，不止列一个开局名，
 * 还用一句话讲清这步/这个布局的战术意图，帮助看懂棋谱每一步。
 *
 * 这里以"分类(category)+开局名子串"双路匹配，命中即返回一段简明攻略文字；
 * 未命中时回退到通用提示，保证任何局面都有话可说、不落空。
 */
