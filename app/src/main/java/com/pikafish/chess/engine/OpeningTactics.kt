        "中炮" to "红首着架中炮直取中路、威逼中卒，是最主流也最具进攻性的开局，攻守围绕中路展开。"
    )

    /** 通用回退语：命中不了具体分类时也能给一句话。 */
    private val FALLBACK_HINT =
        "开局按着既定的子力展开思路行棋，红黑双方围绕中路与河界争夺主动；下一步留意先攻后守的次序与车马炮的协调。"

    /**
     * 为给定的开局分类/名称返回一段战略要点。
     * @param category ECO 分类（如"仙人指路"）
     * @param name 开局全名（如"仙人指路对卒底炮"）
     * @return 战略要点文字；始终非空（有回退语）
     */
    fun hintFor(category: String, name: String): String {
        // 1) 优先按分类名精确/包含匹配
        CATEGORY_HINTS.entries.firstOrNull { (cat, _) ->
            cat == category || (category.isNotEmpty() && category == cat)
        }?.let { return it.value }

        // 2) 再按名称子串匹配（"中炮对屏风马""五七炮..." 等长名）
        CATEGORY_HINTS.entries.firstOrNull { (cat, _) ->
            name.contains(cat)
        }?.let { return it.value }

        // 3) 名称里含"中炮"的兜底
        if (name.contains("中炮")) return CATEGORY_HINTS.getValue("中炮")
        return FALLBACK_HINT
    }
}