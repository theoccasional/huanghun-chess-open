        "仙人指路" to "红先挺兵七路开阔已方子力，暗含试探性与机动性，进退皆宜；黑方多应付以卒底炮、飞象或进卒，属柔性开局，讲究攻守兼备、后手多变。",
        "对兵局" to "双方各挺一路兵卒堂堂正正展开，布局稳健、子力均衡，为达成中局多兵、争夺河界缓攻的常备套路。",
        "飞相局" to "红先飞相稳固中路、偏于防守反击，先求站稳再伺机弈出；黑方常以进马、中炮、过宫炮应对，考验双方对慢结构局的把控。",
        "起马局" to "红先起马活通右翼马路，步伐轻灵、不拘一格，是试探对手喜好的灵活选择，后续可转不同布局阵型。",
        "朝向士角炮" to "士角炮守住三七线弱点、兼通远炮，四平八稳利于后发制人，是稳健型棋手偏好的一路布局。",
        "过宫炮" to "过宫炮架炮于士角兼顾中路与边路，进可攻、退可守，配合上仕上相走成一个稳中带攻的阵势。",
        "金钩炮" to "金钩炮塞住红方进马，颇具对抗性与攻击意图，属冷僻但针对性强的布局，常见于执认真求变之局。",
        "中炮对屏风马" to "红中炮威压中路、黑屏风马双马±拱卒固守主流防御，双方围绕中卒与河界展开最经典、最见功力的阵地战。",
        "五七炮" to "中炮封中主攻，边炮平七瞄黑底象，配合双马抢先，是急攻型棋手最常用的主力布局。",
